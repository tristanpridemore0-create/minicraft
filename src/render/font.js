const CHARS = Object.keys(G);
const INDEX = Object.fromEntries(CHARS.map((c, i) => [c, i]));
const sheets = new Map();

// One strip of every glyph per colour, so text is a drawImage per character.
function sheet(color) {
  let s = sheets.get(color);
  if (s) return s;
  s = document.createElement("canvas");
  s.width = CHARS.length * 8;
  s.height = 8;
  const ctx = s.getContext("2d");
  ctx.fillStyle = color;
  CHARS.forEach((ch, i) => {
    G[ch].forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") ctx.fillRect(i * 8 + x, y, 1, 1);
    });
  });
  sheets.set(color, s);
  return s;
}

export function drawText(ctx, text, x, y, color = "#ffffff", scale = 1) {
  const img = sheet(color);
  const s = String(text).toUpperCase();
  x = Math.round(x);
  y = Math.round(y);
  for (let i = 0; i < s.length; i++) {
    if (s[i] === " ") continue;
    const g = INDEX[s[i]] ?? INDEX["?"];
    ctx.drawImage(img, g * 8, 0, 8, 8, x + i * 8 * scale, y, 8 * scale, 8 * scale);
  }
}

// Text with a one-pixel black drop shadow, for anything drawn over the world.
export function drawTextShadow(ctx, text, x, y, color = "#ffffff") {
  drawText(ctx, text, x + 1, y + 1, "#000000");
  drawText(ctx, text, x, y, color);
}

export function textWidth(text, scale = 1) {
  return String(text).length * 8 * scale;
}

// Break text into lines of at most `max` characters, on spaces where possible.
export function wrapText(text, max = 20) {
  const lines = [];
  let line = "";
  for (const word of String(text).split(" ")) {
    if (line && line.length + 1 + word.length > max) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines;
}

// The blue menu box. Coordinates are in 8-pixel cells, corners inclusive.
export function drawFrame(ctx, title, x0, y0, x1, y1) {
  const x = x0 * 8;
  const y = y0 * 8;
  const w = (x1 - x0 + 1) * 8;
  const h = (y1 - y0 + 1) * 8;
  ctx.fillStyle = C(1);
  ctx.fillRect(x + 1, y, w - 2, h);
  ctx.fillRect(x, y + 1, w, h - 2);
  ctx.fillStyle = C(5);
  ctx.fillRect(x + 1, y + 1, w - 2, h - 2);
  ctx.fillStyle = C(445);
  ctx.fillRect(x + 3, y + 2, w - 6, 1);
  ctx.fillRect(x + 3, y + h - 3, w - 6, 1);
  ctx.fillRect(x + 2, y + 3, 1, h - 6);
  ctx.fillRect(x + w - 3, y + 3, 1, h - 6);
  if (title) {
    ctx.fillStyle = C(5);
    ctx.fillRect(x + 7, y, title.length * 8 + 2, 8);
    drawText(ctx, title, x + 8, y, C(550));
  }
}
